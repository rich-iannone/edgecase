"""Build, lint, and preview the doc graphics.

    python scripts/generate_doc_graphics.py                 # write all + lint
    python scripts/generate_doc_graphics.py --only bfs dfs  # subset (methods or families)
    python scripts/generate_doc_graphics.py --lint          # lint only, nonzero exit on issues
    python scripts/generate_doc_graphics.py --gallery out.html
"""

from __future__ import annotations

import argparse
import html
import importlib
import pkgutil
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

from core import REGISTRY, THEMES, Figure  # noqa: E402
from lint import lint  # noqa: E402

ROOT = HERE.parent.parent
OUT = ROOT / "assets" / "graphs"

FAMILY_ORDER = [
    "mutation", "transforms", "set-ops", "selection", "querying", "data", "traversal", "paths",
    "node-metrics", "graph-metrics", "similarity", "diffusion", "connectivity", "communities",
    "substructures", "enrichment", "predicates", "generators", "layout",
]


def load_figures() -> list[Figure]:
    import figures  # noqa: F401

    for m in pkgutil.iter_modules([str(HERE / "figures")]):
        try:
            importlib.import_module(f"figures.{m.name}")
        except Exception as exc:  # one broken module shouldn't block the rest
            print(f"warning: figures/{m.name}.py failed to import: {exc!r}", file=sys.stderr)
    return sorted(REGISTRY, key=lambda f: (FAMILY_ORDER.index(f.family), f.method))


def snippet(fig: Figure) -> str:
    return (f"![{fig.title}](../assets/graphs/{fig.slug}.light.svg)"
            f'{{.lightbox fig-alt="{fig.alt}" width="100%"}}')


def write_readme(figs: list[Figure]) -> None:
    lines = [
        "# Doc graphics — maintainer index",
        "",
        "Generated by `scripts/generate_doc_graphics.py`. Do not edit by hand.",
        "",
        "Each figure is emitted as `<slug>.light.svg` and `<slug>.dark.svg`, where",
        "the slug is the `Graph` method name with `_` replaced by `-`. Docstrings",
        "reference the `.light.svg` file; the lightbox swaps in the dark sibling.",
        "",
        "See `DOC_GRAPHICS_PLAN.md` at the repo root for the design system.",
        "",
    ]
    fam = None
    for f in figs:
        if f.family != fam:
            fam = f.family
            lines += [f"## {fam}", ""]
        lines += [
            f"### `{f.method}()` — {f.title}",
            "",
            f'<img src="{f.slug}.light.svg" alt="{html.escape(f.alt)}" width="570">',
            "",
            "```markdown",
            snippet(f),
            "```",
            "",
        ]
    (OUT / "README.md").write_text("\n".join(lines))


def write_gallery(figs: list[Figure], path: Path, issues: dict[str, list]) -> None:
    rows = []
    fam = None
    for f in figs:
        if f.family != fam:
            fam = f.family
            n = sum(1 for g in figs if g.family == fam)
            rows.append(f'<h2 id="{fam}">{fam} <small>({n})</small></h2>')
        light = f.scene().render(THEMES[0])
        dark = f.scene().render(THEMES[1])
        iss = issues.get(f.method, [])
        iss_html = ("<ul class=iss>" + "".join(f"<li>{html.escape(str(i))}</li>" for i in iss) + "</ul>"
                    if iss else "")
        rows.append(
            f'<section id="{f.method}"><h3><code>{f.method}()</code> — {html.escape(f.title)}</h3>'
            f'<div class=pair><div class=l>{light}</div><div class=d>{dark}</div></div>'
            f'<p class=alt>{html.escape(f.alt)}</p>{iss_html}</section>'
        )
    nav = " · ".join(f'<a href="#{x}">{x}</a>' for x in FAMILY_ORDER if any(g.family == x for g in figs))
    path.write_text(f"""<!doctype html><meta charset=utf-8><title>edgecase doc graphics</title>
<style>
body{{font:14px system-ui,sans-serif;margin:24px auto;max-width:1600px;color:#1f2328;background:#f6f8fa}}
nav{{position:sticky;top:0;background:#f6f8fa;padding:8px 0;z-index:1}}
h2{{margin-top:40px;border-bottom:1px solid #ccc}} h3{{font-size:14px;margin:18px 0 6px}}
.pair{{display:grid;grid-template-columns:1fr 1fr;gap:12px}}
.pair svg{{width:100%;height:auto;display:block;border:1px solid #d0d7de;border-radius:6px}}
.alt{{color:#57606a;font-size:12px;margin:4px 0}} .iss{{color:#b42318;font:12px ui-monospace,monospace}}
</style><h1>edgecase doc graphics ({len(figs)})</h1><nav>{nav}</nav>{''.join(rows)}""")


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--only", nargs="*", help="method names or family names")
    ap.add_argument("--lint", action="store_true", help="lint only; do not write files")
    ap.add_argument("--gallery", type=Path, help="write an HTML preview gallery here")
    ap.add_argument("--quiet", action="store_true")
    args = ap.parse_args(argv)

    figs = load_figures()
    if args.only:
        want = set(args.only)
        figs = [f for f in figs if f.method in want or f.family in want]

    issues: dict[str, list] = {}
    for f in figs:
        found = lint(f.scene())
        if not f.alt.strip():
            found.append("[alt] missing alt text")
        if "42" in f.alt.replace("4.2", ""):
            found.append("[no-42] alt text uses 42")
        if found:
            issues[f.method] = found

    if not args.lint:
        OUT.mkdir(parents=True, exist_ok=True)
        for f in figs:
            sc = f.scene()
            for theme in THEMES:
                (OUT / f"{f.slug}.{theme.suffix}.svg").write_text(sc.render(theme, f.title))
        if not args.only:
            write_readme(figs)
    if args.gallery:
        write_gallery(figs, args.gallery, issues)

    for m, iss in issues.items():
        for i in iss:
            print(f"{m}: {i}")
    if not args.quiet:
        print(f"{len(figs)} figures, {sum(len(v) for v in issues.values())} lint issues "
              f"in {len(issues)} figures")
    return 1 if issues else 0


if __name__ == "__main__":
    raise SystemExit(main())
